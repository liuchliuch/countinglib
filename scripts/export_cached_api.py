#!/usr/bin/env python3
"""Regenerate selected API types from already built, explicitly mapped artifacts.

This does not build a package or prove mathematical results. Run production
verification first; the explicit artifact request is generated by scripts/verify.py.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
import subprocess
import tempfile
from datetime import datetime, timezone
from pathlib import Path


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(args: argparse.Namespace) -> None:
    root = args.root.resolve()
    index_path = args.index.resolve()
    index = json.loads(index_path.read_text())
    selected = index['declarations']
    index_hash = sha(index_path)
    reference_rows = []
    for reference_path in args.readable_reference:
        reference_rows.extend(json.loads(line) for line in reference_path.read_text().splitlines())
    if bool(reference_rows) != bool(args.readable_output):
        raise ValueError('Provide both --readable-reference and --readable-output')
    by_name = {row['name']: row for row in reference_rows}
    if len(by_name) != len(reference_rows):
        raise ValueError('Readable reference names are duplicated')
    artifact_request = json.loads(args.artifact_request.read_text())
    arts = artifact_request['import_artifacts']
    if args.artifact_root:
        old = str(args.artifact_root.resolve()) + '/'
        arts = {name: [[str(root) + '/' + path[len(old):] if path.startswith(old) else path
                        for path in group] for group in groups]
                for name, groups in arts.items()}
    for row in selected:
        source = root / row['source_path']
        if sha(source) != row['source_sha256']:
            raise ValueError(f"Curated source changed: {row['source_path']}; review its contract first")
    missing = [path for groups in arts.values() for group in groups for path in group
               if not Path(path).is_file()]
    if missing:
        raise FileNotFoundError(f'{len(missing)} mapped artifacts are missing; first: {missing[0]}')
    all_names = list(dict.fromkeys([row['name'] for row in selected] + list(by_name)))
    request = {'names': all_names,
               'roots': sorted({row['provider_module'] for row in selected} | {row['module'] for row in reference_rows}),
               'import_artifacts': arts}
    args.types.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='countinglib-api-', dir=args.types.parent) as tmp:
        request_path = Path(tmp) / 'request.json'
        request_path.write_text(json.dumps(request) + '\n')
        raw_output = Path(tmp) / 'actual-types.jsonl'
        command = [str(root / 'scripts/lake'), 'env', 'lean', '--run',
                   str(args.exporter.resolve()), str(request_path), str(raw_output)]
        started = datetime.now(timezone.utc).isoformat()
        result = subprocess.run(command, cwd=root, capture_output=True, text=True,
                                env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1'})
        args.log.parent.mkdir(parents=True, exist_ok=True)
        args.log.write_text(result.stdout + result.stderr)
        if result.returncode:
            raise RuntimeError(f'Actual Lean exporter exit {result.returncode}; see {args.log}')
        raw_lines = raw_output.read_text().splitlines()
        actual_list = [json.loads(line) for line in raw_lines]
        raw_by_name = {json.loads(line)['name']: line for line in raw_lines}
    actual = {row['name']: row for row in actual_list}
    if len(actual) != len(actual_list) or set(actual) != set(all_names):
        raise ValueError('Actual and selected name sets differ')
    for row in selected:
        value = actual[row['name']]
        if value['module'] != row['provider_module'] or value['type'] != row['type']:
            raise ValueError(f"Actual kernel type/provider changed: {row['name']}; review first")
        row.update({key: value[key] for key in ['type_pp', 'type_pp_all', 'type']})
    args.types.write_text(''.join(raw_by_name[row['name']] + '\n' for row in selected))
    if reference_rows:
        readable = []
        for row in reference_rows:
            value = actual[row['name']]
            if value['module'] != row['module'] or value['type'] != row['type']:
                raise ValueError(f"Actual readable kernel type/provider changed: {row['name']}")
            readable.append({key: value[key] for key in ['name', 'module', 'type_pp', 'type']})
        args.readable_output.write_text(''.join(json.dumps(row, ensure_ascii=False, separators=(',', ':')) + '\n' for row in readable))
    index['status']['full_type_export_sha256'] = sha(args.types)
    args.output_index.write_text(json.dumps(index, ensure_ascii=False, indent=2) + '\n')
    receipt = {'status': 'passed', 'started_utc': started,
               'finished_utc': datetime.now(timezone.utc).isoformat(),
               'lean_export_exit_code': result.returncode,
               'declarations': len(selected),
               'input_index_sha256': index_hash,
               'output_index_sha256': sha(args.output_index),
               'types_sha256': sha(args.types), 'exporter_sha256': sha(args.exporter),
               'artifact_request_sha256': sha(args.artifact_request),
               'mode': 'read-only imports of existing explicitly mapped compiled artifacts; no package build',
               'complete_types': 'actual Expr DAG and pp.all; readable view may use standard Lean proof/implicit omissions',
               'limits': 'Type extraction does not replace source build or transitive-axiom verification.'}
    if reference_rows:
        receipt.update({'readable_declarations': len(reference_rows), 'readable_sha256': sha(args.readable_output),
                        'readable_bindings': 'Every actual module and Expr DAG matches the original full type export.'})
    args.receipt.write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps(receipt, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('.'))
    parser.add_argument('--index', type=Path, default=Path('data/api/core-index.json'))
    parser.add_argument('--artifact-request', type=Path, required=True)
    parser.add_argument('--artifact-root', type=Path,
                        help='Original checkout root to remap to --root, if different')
    parser.add_argument('--exporter', type=Path, default=Path(__file__).with_name('ExportApiTypes.lean'))
    parser.add_argument('--readable-reference', type=Path, action='append', default=[],
                        help='Existing full type JSONL to produce a readable overlay for; repeatable')
    parser.add_argument('--readable-output', type=Path)
    parser.add_argument('--types', type=Path, required=True)
    parser.add_argument('--output-index', type=Path, required=True)
    parser.add_argument('--log', type=Path, required=True)
    parser.add_argument('--receipt', type=Path, required=True)
    run(parser.parse_args())

if __name__ == '__main__':
    main()
